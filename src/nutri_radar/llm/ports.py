"""Порт языковой модели.

Единственное, что знают о моделях слайсы пайплайна. Конкретный адаптер
подставляет composition root по значению `LLM__PROVIDER` — ни `extract`,
ни `evals`, ни `agent` не импортируют `ollama` или `anthropic` напрямую
(см. ARCHITECTURE.md, антипаттерн «конкретный адаптер внутри слайса»).

Порт сознательно узкий: один метод. Расширять по факту потребности, а не
проектировать впрок.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any, Protocol, runtime_checkable

from nutri_radar.llm.models import LLMResponse


@runtime_checkable
class StructuredLLM(Protocol):
    """Генерация, ограниченная JSON-схемой.

    Ограничение схемой — не просьба в промпте, а параметр генерации: свободный
    JSON от модели 3B ненадёжен (раздел 3a брифа).
    """

    @property
    def model_name(self) -> str:
        """Имя модели. Уезжает в `product_extraction` рядом с результатом."""
        ...

    async def generate(
        self,
        prompt: str,
        *,
        json_schema: dict[str, Any],
        max_output_tokens: int | None = None,
    ) -> LLMResponse:
        """Получить ответ, соответствующий схеме.

        Raises:
            LLMUnavailableError: модель недоступна или вернула отказ.
                Такую ошибку имеет смысл ретраить.
            ExtractionError: модель ответила, но ответ непригоден — не
                разбирается или оборван лимитом вывода. Ретрай не поможет.
        """
        ...


@runtime_checkable
class EmbeddingModel(Protocol):
    """Превращение текста в вектор.

    Второй порт, а не метод в `StructuredLLM`: это разные модели с разным
    жизненным циклом. На 6 ГБ VRAM они не помещаются одновременно, и слайс,
    которому нужны только эмбеддинги, не должен зависеть от интерфейса
    генерации — иначе `retrieval` (M5) потянет за собой JSON-схемы,
    которые ему не нужны.

    Порт принимает список, а не одну строку: у Ollama и у облачных провайдеров
    батч — это один запрос, и адаптер, умеющий только по одному, превращает
    прогон корпуса в тысячи round-trip-ов.
    """

    @property
    def model_name(self) -> str:
        """Имя модели. Уезжает рядом с векторами: эмбеддинги разных моделей
        несравнимы, и вектор без имени модели — это вектор неизвестно чего."""
        ...

    @property
    def dimensions(self) -> int:
        """Размерность вектора. Колонка `vector(N)` в pgvector объявляется
        по ней, и расхождение обнаружится вставкой, а не проверкой."""
        ...

    async def embed(self, texts: Sequence[str]) -> list[list[float]]:
        """Векторизовать батч текстов.

        Порядок ответа совпадает с порядком входа — на этом держится
        сопоставление вектора с продуктом.

        Raises:
            LLMUnavailableError: модель недоступна. Имеет смысл ретраить.
            ExtractionError: модель ответила, но ответ непригоден —
                не тот размер вектора или батч не совпал по длине.
                Ретрай не поможет.
        """
        ...
