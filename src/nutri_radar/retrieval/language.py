"""Определение языка текста по алфавиту.

Отдельный модуль, потому что признак нужен в двух местах по разные
стороны зависимости: `metrics.py` считает по нему долю ответов на языке
вопроса, а `rag.py` решает по нему, к какому языку принуждать модель.
`metrics.py` уже импортирует `rag.py` — положить признак в метрики
значило бы замкнуть импорты в кольцо. Общий признак выносится в общий
модуль, как требует правило о границах зависимостей.

**Почему признак, а не библиотека.** На паре «русский и английский»
алфавит различает языки безошибочно: у них не пересекаются буквы.
Статистические определители языка на коротком тексте ошибаются, а
короткий текст здесь норма — ответ в две строки со штрихкодом.

**И чего признак не умеет.** Немецкий и французский он от английского
не отличает вовсе: латиница у всех троих. Это не гипотетическое
ограничение — в эталоне поиска есть запросы на обоих. Поэтому языки,
которые признак действительно различает, перечислены явно
в `RESOLVABLE_LANGUAGES`, и всё, что снаружи этого множества, обязано
обрабатываться как «неизвестно», а не как «английский».
"""

from __future__ import annotations

import re

# Язык определить не удалось: текст слишком короткий, букв поровну,
# или язык вне того, что признак различает.
UNDETERMINED = ""

# Языки, которые признак по алфавиту действительно различает.
# Всё остальное — латиница, неотличимая от английского.
RESOLVABLE_LANGUAGES = frozenset({"ru", "en"})

# Названия для промпта: модель понимает «Russian» лучше, чем «ru».
LANGUAGE_NAMES = {"ru": "Russian", "en": "English"}

_CYRILLIC = re.compile(r"[\u0400-\u04FF]")
_LATIN = re.compile(r"[A-Za-z]")


def detect_language(text: str, *, min_letters: int) -> str:
    """Определить язык текста по алфавиту: кириллица против латиницы.

    Args:
        text: текст, язык которого нужно определить.
        min_letters: сколько букв должно быть в тексте, чтобы судить
            о языке. Ниже порога возвращается `UNDETERMINED`: на трёх
            буквах признак меряет не язык, а случайность.

    Returns:
        `"ru"`, `"en"` или `UNDETERMINED`.

    Note:
        `"en"` здесь означает «латиница», а не «точно английский».
        Для немецкого и французского текста функция тоже вернёт `"en"` —
        это граница метода, и вызывающий код обязан о ней знать.
    """
    cyrillic = len(_CYRILLIC.findall(text))
    latin = len(_LATIN.findall(text))
    if cyrillic + latin < min_letters:
        return UNDETERMINED
    if cyrillic == latin:
        # Ровно поровну — это не «оба», это «непонятно». Выбрать один
        # означало бы записать монетку в результат.
        return UNDETERMINED
    return "ru" if cyrillic > latin else "en"


def is_cyrillic(text: str) -> bool:
    """Написан ли текст преимущественно кириллицей.

    Отдельно от `detect_language` и намеренно без порога длины: вопрос
    пользователя бывает в три слова, а кириллица в нём однозначна —
    ни один латинский язык её не использует. Ошибиться здесь можно
    только в одну сторону (не распознать русский), и эта ошибка
    безопасна: она возвращает поведение к `rag_v1`.
    """
    cyrillic = len(_CYRILLIC.findall(text))
    return cyrillic > 0 and cyrillic > len(_LATIN.findall(text))
