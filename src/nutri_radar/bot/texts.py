def all_texts() -> list[str]:
    """Все тексты, которые бот пишет от себя.

    Существует ради теста: проверка на оценочные ярлыки должна охватывать
    и то, что допишут потом, а не только известные сегодня константы.
    """
    return [
        value
        for name, value in globals().items()
        if name.isupper() and isinstance(value, str) and not name.startswith("_")
    ]
