"""Границы формулировок: что проект обязан сказать и чего говорить не должен.

Раздел «Границы продукта» брифа: система показывает, **что написано
в составе**, и ссылается на данные. Она не медицинский и не диетологический
советчик — не даёт рекомендаций по питанию, не строит диеты, не считает
нормы под человека.

Отсюда запрет на оценочные ярлыки: «вредно», «плохой состав», «нельзя есть».
Правильная формулировка описательная и проверяемая: «в составе 4 разные формы
сахара», «оценка по базе — C», «группа переработки NOVA — 4». Разница не
стилистическая: «в составе 4 формы сахара» — это факт из данных, который
читатель может перепроверить по штрихкоду, а «слишком сладко» — суждение,
которое проект не имеет оснований выносить.

**Почему это модуль, а не пункт в code review.** Ярлык попадает в продукт
не решением, а по инерции — одной строкой в шаблоне ответа, которую никто
не перечитывал полгода. Список лежит здесь, и тексты всех трёх точек входа
(API, бот, MCP) проверяются против него автоматически. Требование брифа
обязано ломать тест, а не ждать вычитки.

**Проверяются наши формулировки, а не данные источника.** В составе продукта
из Open Food Facts законно встречается «натуральный ароматизатор» или
«диетический продукт» — это цитата с этикетки, и вырезать её значило бы
искажать данные. Запрет касается текста, который проект пишет **от себя**:
шаблонов ответа, подписей полей, сообщений бота. Цитируемый состав из-под
проверки выведен сознательно.

Список намеренно не претендует на полноту: он ловит типовые формулировки,
а не заменяет понимание границы. Пополнять его следует при каждом
пойманном случае.
"""

from __future__ import annotations

import re

# =============================================================================
# Обязательное: атрибуция и дисклеймер
# =============================================================================
#
# Лицензия ODbL требует указывать источник — это юридическое обязательство,
# а не жест вежливости. Бриф уточняет, где именно: **в первом сообщении бота**,
# а не в подвале, куда никто не долистывает.
#
# Дисклеймер стоит рядом по той же причине: данные краудсорсинговые, их
# заполняют люди, и они бывают неполными или неверными. Пользователь, который
# принимает решение по карточке, обязан знать это до решения, а не после.

ATTRIBUTION = (
    "Данные: Open Food Facts (openfoodfacts.org), лицензия ODbL. "
    "Проект не связан с Open Food Facts."
)

# Формулировка обходит слово «диетологический» намеренно. Проверка на
# оценочные ярлыки ищет основы слов и не понимает отрицаний: «а не
# диетологический советчик» она засчитала бы как нарушение, хотя это ровно
# то самое отрицание. Чинить это следует переписыванием текста, а не
# ослаблением проверки — иначе список запретов постепенно опустеет.
DISCLAIMER = (
    "Данные краудсорсинговые: их заполняют люди, и они бывают неполными "
    "или неверными. Это инструмент прозрачности состава, а не медицинский "
    "советчик: он не даёт рекомендаций по питанию, а показывает, что "
    "написано в составе, и ссылается на штрихкод, по которому это можно "
    "проверить."
)


def attribution_block() -> str:
    """Атрибуция и дисклеймер одним блоком.

    Одна функция на все точки входа: разойтись формулировкам негде,
    и проверять их достаточно в одном месте.
    """
    return f"{ATTRIBUTION}\n\n{DISCLAIMER}"


# =============================================================================
# Запрещённое: оценочные ярлыки
# =============================================================================

# Оценочные ярлыки. Проверка идёт по основам слов, чтобы падеж и род не
# создавали дыр: «вредный», «вредная», «вредно» ловятся одной записью.
EVALUATIVE_LABELS: tuple[str, ...] = (
    "вред",  # вредно, вредный, вредность
    # «Полезно» — оценка ровно в той же мере, что и «вредно». Основа «польз»
    # не годится: она ловит безобидного «пользователя», и тест начал бы
    # падать на слове, к границам продукта отношения не имеющем.
    "полезн",
    "полезен",
    "плохой состав",
    "плохая еда",
    "хорошая еда",
    "здоровая еда",
    "нездоров",
    "нельзя есть",
    "не стоит есть",
    "опасн",
    "токсич",
    "натуральн",  # «натуральный» в маркетинговом смысле — оценка, а не факт
    "химия",
    "правильное питание",
    "диет",  # диета, диетический — проект не строит диет
    "худе",  # худеть, худеющим
    "калорийность в норме",
    "норма потребления",
    "рекомендуем",
    "советуем",
)

# Границы слова тут не годятся: ищем основы, а не леммы. Зато нужен
# регистронезависимый поиск — ярлык в начале предложения тот же ярлык.
_PATTERN = re.compile("|".join(re.escape(label) for label in EVALUATIVE_LABELS), re.IGNORECASE)


def evaluative_labels_in(text: str) -> list[str]:
    """Найти оценочные ярлыки в тексте.

    Возвращает то, что нашлось, а не булев флаг: в тесте важно увидеть,
    какое именно слово попало в шаблон, иначе отладка превращается
    в перечитывание всего текста.
    """
    return sorted({match.group(0).lower() for match in _PATTERN.finditer(text)})
