"""Тесты защиты от чтения настоящих секретов разработчика.

Проверяется не приложение, а тестовое окружение — автоюзная фикстура
`_no_real_secrets` из `conftest.py`. Повод конкретный: `DB__PASSWORD`
добавили в общий список затираемых ключей, и интеграционные тесты
потеряли пароль к базе. Юнит-тесты при этом остались зелёными, поэтому
дефект дожил до CI и лежал там красным.

Правило, которое здесь закрепляется: настоящие секреты (токен бота, ключ
Anthropic, ключ Langfuse) затираются у всех тестов без исключения, а пароль
к базе — у всех, кроме помеченных маркером `integration`, потому что без него
интеграционная фикстура не дойдёт до контейнера.
"""

from __future__ import annotations

import os

import pytest

from tests.conftest import keys_to_blank

# Ключи настоящих секретов: у них нет ни одного сценария, где тесту нужно
# увидеть значение с машины разработчика.
_ВСЕГДА_ЗАТИРАЮТСЯ = ("BOT__TOKEN", "ANTHROPIC__API_KEY", "LANGFUSE__SECRET_KEY")


class TestСписокЗатираемыхКлючей:
    """Правило в чистом виде, без поднятой базы и без маркеров."""

    def test_обычный_тест_не_видит_ни_одного_секрета(self):
        ключи = keys_to_blank(is_integration=False)

        for ключ in _ВСЕГДА_ЗАТИРАЮТСЯ:
            assert ключ in ключи, f"{ключ} обязан затираться"
        assert "DB__PASSWORD" in ключи

    def test_интеграционному_тесту_оставлен_только_пароль_бд(self):
        ключи = keys_to_blank(is_integration=True)

        assert "DB__PASSWORD" not in ключи, (
            "Интеграционные тесты подключаются к настоящему Postgres: "
            "с пустым паролем фикстура migrated_database падает "
            "с InvalidPasswordError, и CI краснеет на шаге интеграционных."
        )
        for ключ in _ВСЕГДА_ЗАТИРАЮТСЯ:
            assert ключ in ключи, f"{ключ} — настоящий секрет, интеграционному тесту он не нужен"

    def test_разница_между_режимами_ровно_в_одном_ключе(self):
        """Послабление обязано быть точечным.

        Без этой проверки в исключение для интеграционных тестов со временем
        уедет ещё какой-нибудь ключ, и защита протечёт молча.
        """
        обычные = set(keys_to_blank(is_integration=False))
        интеграционные = set(keys_to_blank(is_integration=True))

        assert обычные - интеграционные == {"DB__PASSWORD"}
        assert интеграционные - обычные == set()


class TestФикстураПрименяется:
    """Список ключей верный — но применяет ли его фикстура на самом деле."""

    def test_в_обычном_тесте_пароль_бд_затёрт(self):
        assert os.environ["DB__PASSWORD"] == ""

    def test_в_обычном_тесте_настоящие_секреты_затёрты(self):
        for ключ in _ВСЕГДА_ЗАТИРАЮТСЯ:
            assert os.environ[ключ] == ""


@pytest.mark.integration
class TestФикстураПрименяетсяКИнтеграционным:
    """Ровно тот случай, который сломался в CI.

    Маркер тут стоит не ради базы — она этим тестам не нужна, — а потому что
    поведение фикстуры зависит от маркера, и проверить его можно только изнутри
    помеченного теста. Запускается вместе с остальными интеграционными:
    `uv run pytest -m integration`.
    """

    def test_пароль_бд_не_затёрт(self):
        пароль = os.environ.get("DB__PASSWORD")

        assert пароль != "", (
            "DB__PASSWORD затёрт у интеграционного теста — подключение "
            "к Postgres упадёт с InvalidPasswordError"
        )

    def test_настоящие_секреты_всё_равно_затёрты(self):
        for ключ in _ВСЕГДА_ЗАТИРАЮТСЯ:
            assert os.environ[ключ] == "", (
                f"{ключ} виден интеграционному тесту — послабление для пароля "
                "к базе не должно распространяться на настоящие секреты"
            )
